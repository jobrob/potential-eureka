# Orchestrator
# ---------------------------------------------------------------------------


@dataclass
class IterationRecord:
    """One iteration's outcome (for the run report)."""

    iteration: int
    data_path: str
    union_path: str
    model_path: str
    gate: GateMetric
    retained: bool
    reason: str


def run_iteration(args: argparse.Namespace) -> dict:
    """Run bounded policy iteration; return a report dict.

    Starts from the A1/A2 seed V (``--seed-model``) and its dataset
    (``--seed-data``). The seed V is gated first to establish the baseline the
    first iteration must strictly beat (best-checkpoint preservation: the shipped
    V is never worse than this). Then, up to ``--iterations`` (capped at 2) times:
    generate learned-policy data, refit on the union of all data so far, re-gate,
    apply the stop rule. The best-gating V is copied to ``--out`` and reported.
    """
    iters = min(args.iterations, 2)  # HARD cap -- never more than 2 (A3 §Stop rule)
    if iters < args.iterations:
        print(
            f"NOTE: requested {args.iterations} iterations; A3 hard-caps at 2."
        )
    os.makedirs(args.workdir, exist_ok=True)

    # The accumulating union of datasets: starts with the A1 seed dataset, grows
    # by one round per retained-or-discarded iteration (we always train on the
    # union of EVERYTHING generated, even a round we ultimately discard, because
    # the discard decision is about the *gate*, not the data quality).
    union_paths: list[str] = [args.seed_data]

    # Baseline: gate the seed V so iteration 1 has something to strictly beat.
    print("\n--- gating seed V (the A2 baseline to beat) ---")
    best_model = args.seed_model
    best_gate = _gate(
        value_model=best_model,
        gate_games=args.gate_games,
        horizon=args.horizon,
        dets=args.dets,
        top_k=args.top_k,
        sim_budget=args.sim_budget,
        seed=args.seed,
    )
    print(f"  seed gate: {best_gate.as_dict()}")

    records: list[IterationRecord] = []
    t0 = time.perf_counter()
    for it in range(1, iters + 1):
        print(f"\n=== value-iteration round {it}/{iters} ===")
        data_path = os.path.join(args.workdir, f"round{it}.npz")
        union_path = os.path.join(args.workdir, f"union{it}.npz")
        model_path = os.path.join(args.workdir, f"value_round{it}.zip")

        # (1) generate with the CURRENT best V's search agent.
        print(f"  [1/3] generating learned-policy data (V={best_model})")
        gen_summary = _generate(
            value_model=best_model,
            out=data_path,
            train_tracks=args.train_tracks,
            val_tracks=args.val_tracks,
            rollouts=args.rollouts,
            game_seed=args.game_seed + it * 100_000,
            horizon=args.horizon,
            dets=args.dets,
            top_k=args.top_k,
            sim_budget=args.sim_budget,
        )
        print(
            f"        generated {gen_summary['n_rows']} rows "
            f"({gen_summary['races_dropped_max_rounds']} races dropped)"
        )

        # (2) refit on the UNION of all data so far (seed + every prior round).
        union_paths.append(data_path)
        merge_summary = _merge_datasets(union_paths, union_path)
        print(
            f"  [2/3] refitting V on union of {merge_summary['n_sources']} "
            f"datasets ({merge_summary['n_rows']} rows)"
        )
        _refit(
            data=union_path,
            out=model_path,
            epochs=args.epochs,
            device=args.device,
            seed=args.seed,
            loss=args.loss,
            net=args.net,
        )

        # (3) re-gate and apply the stop rule.
        print("  [3/3] gating refit V on the held-out band")
        gate = _gate(
            value_model=model_path,
            gate_games=args.gate_games,
            horizon=args.horizon,
            dets=args.dets,
            top_k=args.top_k,
            sim_budget=args.sim_budget,
            seed=args.seed,
        )
        improved = gate.strictly_improves_on(best_gate)
        print(f"        round {it} gate: {gate.as_dict()}")
        print(f"        best   gate:    {best_gate.as_dict()}")

        if improved:
            reason = "strict improvement -> retained, becomes new best"
            best_gate = gate
            best_model = model_path
            retained = True
            print(f"        -> {reason}")
        else:
            reason = "no strict improvement -> discarded, stop iterating"
            retained = False
            print(f"        -> {reason}")

        records.append(
            IterationRecord(
                iteration=it,
                data_path=data_path,
                union_path=union_path,
                model_path=model_path,
                gate=gate,
                retained=retained,
                reason=reason,
            )
        )
        if not improved:
            break  # one-step no-improvement stop rule

    elapsed = time.perf_counter() - t0

    # Ship the best-gating V. If no iteration improved on the seed, the seed V is
    # shipped verbatim (best-checkpoint preservation: never worse than A2's V).
    import shutil

    os.makedirs(os.path.dirname(os.path.abspath(args.out)) or ".", exist_ok=True)
    shutil.copyfile(best_model, args.out)
    best_meta = os.path.splitext(best_model)[0] + ".meta.json"
    if os.path.exists(best_meta):
        shutil.copyfile(best_meta, os.path.splitext(args.out)[0] + ".meta.json")

    report = {
        "out": args.out,
        "best_model_source": best_model,
        "best_is_seed": best_model == args.seed_model,
        "best_gate": best_gate.as_dict(),
        "iterations_run": len(records),
        "iterations_cap": iters,
        "elapsed_s": round(elapsed, 1),
        "rounds": [
            {
                "iteration": r.iteration,
                "gate": r.gate.as_dict(),
                "retained": r.retained,
                "reason": r.reason,
                "model_path": r.model_path,
            }
            for r in records
        ],
    }
    return report


def _print_report(report: dict) -> None:
    print("\n=== value_iterate summary ===")
    print(f"  iterations run: {report['iterations_run']} (cap {report['iterations_cap']})")
    for r in report["rounds"]:
        tag = "RETAINED" if r["retained"] else "DISCARDED"
        print(
            f"    round {r['iteration']}: gate={r['gate']}  [{tag}] -- {r['reason']}"
        )
    src = "SEED V (no round improved)" if report["best_is_seed"] else report["best_model_source"]
    print(f"  best-gating V: {src}")
    print(f"    gate: {report['best_gate']}")
    print(f"  shipped -> {report['out']}")
    print(f"  total time: {report['elapsed_s']}s")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed-model", type=str, required=True,
                        help="A1/A2 seed V checkpoint (the baseline to beat + the "
                             "driver of iteration 1's data)")
    parser.add_argument("--seed-data", type=str, required=True,
                        help="A1 seed value .npz (the base of the training union)")
    parser.add_argument("--out", type=str, default="checkpoints/value_iterated.zip",
                        help="output path for the best-gating V (sidecar alongside)")
    parser.add_argument("--workdir", type=str, default="runs/value_iterate",
                        help="scratch dir for per-round data/union/checkpoints")
    parser.add_argument("--iterations", type=int, default=2,
                        help="iterations to attempt (HARD-capped at 2 by A3)")
    parser.add_argument("--train-tracks", type=int, default=40,
                        help="TRAIN tracks per generated round")
    parser.add_argument("--val-tracks", type=int, default=12,
                        help="VAL tracks per generated round")
    parser.add_argument("--rollouts", type=int, default=1,
                        help="MC rollouts per track per round")
    parser.add_argument("--gate-games", type=int, default=24,
                        help="held-out tracks for the gate (900_000+ band)")
    parser.add_argument("--epochs", type=int, default=30,
                        help="train_value epochs per refit")
    parser.add_argument("--horizon", type=int, default=2,
                        help="LookaheadAgent rollout depth (gen + gate)")
    parser.add_argument("--dets", type=int, default=2,
                        help="LookaheadAgent determinizations (gen + gate)")
    parser.add_argument("--top-k", type=int, default=6,
                        help="LookaheadAgent top-k branching cap (A2: top_k=6 is "
                             "'free accuracy' and keeps generation affordable)")
    parser.add_argument("--sim-budget", type=int, default=None,
                        help="LookaheadAgent per-move clone budget")
    parser.add_argument("--loss", type=str, default="mse", choices=["mse", "huber"],
                        help="train_value regression loss")
    parser.add_argument("--net", type=str, default="default",
                        choices=["default", "small", "large"],
                        help="train_value net-size profile")
    parser.add_argument("--device", type=str, default="auto",
                        help="auto|cuda|cpu for train_value")
    parser.add_argument("--game-seed", type=int, default=7000,
                        help="base game seed for data generation")
    parser.add_argument("--seed", type=int, default=0,
                        help="base seed for the gate (and trainer)")
    args = parser.parse_args()

    print(
        f"value_iterate: seed_model={args.seed_model} seed_data={args.seed_data} "
        f"iterations={min(args.iterations, 2)} (cap 2) "
        f"train_tracks={args.train_tracks} val_tracks={args.val_tracks} "
        f"gate_games={args.gate_games} (codec v{CODEC_VERSION}, OBS_DIM={OBS_DIM})"
    )
    report = run_iteration(args)
    _print_report(report)


if __name__ == "__main__":
    from _runlog import run_main

    run_main("value_iterate", main)
