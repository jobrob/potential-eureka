# ---------------------------------------------------------------------------
# Gate metric
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class GateMetric:
    """The A3 stop-rule metric: ``(worst_case_limit1_spins, rounds_to_finish)``.

    Lower is better on both axes. ``worst_case_limit1_spins`` is the max
    spins-per-limit-1-pass over games (``_AgentAgg.spin_stats(1)[2]``) -- the
    death-spiral signal the pooled mean hides; ``rounds_to_finish`` is the mean
    rounds over finishers (``_AgentAgg.mean_rounds()``), the primary lap-time gate.

    NaN handling: a NaN axis (e.g. no limit-1 passes sampled, or no finishers)
    is treated as "not an improvement and not a regression" on that axis -- it
    cannot drive a strict improvement, and a real (non-NaN) value never counts as
    regressing relative to a NaN baseline. This keeps the stop rule conservative:
    a round only retains on a *real* measured improvement.
    """

    worst_case_limit1_spins: float
    rounds_to_finish: float

    def strictly_improves_on(self, other: "GateMetric") -> bool:
        """True iff this gate strictly improves on ``other`` per the A3 rule.

        Strict improvement = (rounds-to-finish decreases OR worst-case limit-1
        spins decreases) with NEITHER axis regressing. A NaN axis neither
        improves nor regresses (see class docstring), so it is inert.
        """
        if _regresses(self.rounds_to_finish, other.rounds_to_finish):
            return False
        if _regresses(self.worst_case_limit1_spins, other.worst_case_limit1_spins):
            return False
        improved = _improves(
            self.rounds_to_finish, other.rounds_to_finish
        ) or _improves(
            self.worst_case_limit1_spins, other.worst_case_limit1_spins
        )
        return improved

    def as_dict(self) -> dict:
        return {
            "worst_case_limit1_spins": self.worst_case_limit1_spins,
            "rounds_to_finish": self.rounds_to_finish,
        }


def _improves(new: float, old: float, eps: float = 1e-9) -> bool:
    """True iff ``new`` is strictly lower than ``old`` (both real, lower=better)."""
    if new != new or old != old:  # NaN on either side -> not an improvement
        return False
    return new < old - eps


def _regresses(new: float, old: float, eps: float = 1e-9) -> bool:
    """True iff ``new`` is strictly higher than ``old`` (both real, lower=better)."""
    if new != new or old != old:  # NaN on either side -> not a regression
        return False
    return new > old + eps


# ---------------------------------------------------------------------------
# The three reused steps (generate / refit / gate), each a thin wrapper
# ---------------------------------------------------------------------------


def _generate(
    *,
    value_model: str,
    out: str,
    train_tracks: int,
    val_tracks: int,
    rollouts: int,
    game_seed: int,
    horizon: int,
    dets: int,
    top_k: int | None,
    sim_budget: int | None,
) -> dict:
    """Generate one round of MC value data driven by the learned-leaf agent.

    Thin wrapper over A1's ``gen_value_data.generate_dataset`` with
    ``policy=learned`` -- seat 0 is the A2 ``LookaheadAgent(leaf_value="learned")``
    loaded from ``value_model``. Returns the generator's stats summary.
    """
    gen_args = argparse.Namespace(
        out=out,
        train_tracks=train_tracks,
        val_tracks=val_tracks,
        rollouts=rollouts,
        game_seed=game_seed,
        policy="learned",
        value_model=value_model,
        horizon=horizon,
        dets=dets,
        top_k=top_k,
        sim_budget=sim_budget,
    )
    return gen_value_data.generate_dataset(gen_args)


def _merge_datasets(paths: list[str], out: str) -> dict:
    """Materialize the UNION of value ``.npz`` datasets as a single ``.npz``.

    Concatenates the parallel arrays (``obs``, ``rounds_remaining``,
    ``corner_limit_at_state``, ``track_seed``, ``split``) row-wise across all
    ``paths`` and writes a merged ``.value.json`` sidecar so the unchanged
    ``train_value._load_dataset`` (which validates the sidecar's codec_version)
    consumes the union directly. The per-row track-disjoint ``split`` is carried
    verbatim, so the union preserves the train/val disjointness of each source
    (the TRAIN/VAL seed bands are identical and disjoint across all rounds by
    construction). Returns a stats dict (n_rows, per-source counts).
    """
    cols = {
        "obs": [],
        "rounds_remaining": [],
        "corner_limit_at_state": [],
        "track_seed": [],
        "split": [],
    }
    per_source = []
    for p in paths:
        data = np.load(p)
        n = int(data["obs"].shape[0])
        if data["obs"].shape[1] != OBS_DIM:
            raise ValueError(
                f"{p}: obs {data['obs'].shape} != OBS_DIM={OBS_DIM}"
            )
        for k in cols:
            cols[k].append(data[k])
        per_source.append({"path": p, "n_rows": n})

    merged = {k: np.concatenate(v, axis=0) for k, v in cols.items()}

    os.makedirs(os.path.dirname(os.path.abspath(out)) or ".", exist_ok=True)
    np.savez_compressed(out, **merged)

    n_rows = int(merged["obs"].shape[0])
    meta = {
        "codec_version": CODEC_VERSION,
        "obs_dim": OBS_DIM,
        "generator_policy": "union(value_iterate)",
        "num_players": 1,
        "n_rows": n_rows,
        "sources": per_source,
    }
    meta_path = os.path.splitext(out)[0] + ".value.json"
    with open(meta_path, "w", encoding="utf-8") as fh:
        json.dump(meta, fh, indent=2, sort_keys=True)

    return {
        "out": out,
        "n_rows": n_rows,
        "n_sources": len(paths),
        "per_source": per_source,
    }


def _refit(
    *,
    data: str,
    out: str,
    epochs: int,
    device: str,
    seed: int,
    loss: str,
    net: str,
) -> dict:
    """Refit V on a (union) dataset via A1's unchanged ``train_value``.

    A thin wrapper -- no trainer logic changes. Returns the trainer's summary.
    """
    train_args = argparse.Namespace(
        data=data,
        out=out,
        epochs=epochs,
        batch=256,
        lr=3e-4,
        loss=loss,
        eval_every=max(1, epochs // 2),
        patience=8,
        net=net,
        device=device,
        seed=seed,
    )
    return train_value.train_value(train_args)


def _gate(
    *,
    value_model: str,
    gate_games: int,
    horizon: int,
    dets: int,
    top_k: int | None,
    sim_budget: int | None,
    seed: int,
) -> GateMetric:
    """Gate a V checkpoint on the held-out 900_000+ band via ``eval_search``.

    Calls A2's ``eval_search._run_field`` programmatically (no stdout parsing) on
    the SOLO field -- the primary gate -- with a single ``LookaheadLearned``
    contender loaded from ``value_model``. Reads the two stop-rule axes off the
    returned ``_AgentAgg``: ``mean_rounds()`` and ``spin_stats(1)[2]``.
    """
    track_seeds = [eval_search._HELDOUT_BASE + i for i in range(gate_games)]

    def make_learned():
        return LookaheadAgent(
            name="LookaheadLearned",
            horizon=horizon,
            n_determinizations=dets,
            leaf_value="learned",
            value_model_path=value_model,
            top_k=top_k,
            sim_budget=sim_budget,
        )

    aggs, _profiles = eval_search._run_field(
        {"LookaheadLearned": make_learned},
        track_seeds=track_seeds,
        num_players=1,
        game_seed_base=seed,
    )
    agg = aggs["LookaheadLearned"]
    _, _, worst_limit1 = agg.spin_stats(1)
    return GateMetric(
        worst_case_limit1_spins=float(worst_limit1),
        rounds_to_finish=float(agg.mean_rounds()),
    )


