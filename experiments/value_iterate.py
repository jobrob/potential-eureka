"""Sprint A3 (Option A) -- bounded light policy iteration for the learned leaf.

Refit ``V`` on trajectories generated by the *current* ``leaf_value="learned"``
search agent (better-than-heuristic driving) so V can credit lines the heuristic
never demonstrates -- **one or two bounded rounds with a hard stop rule, never
open-ended self-play** (the 8C collapse failure mode, memory
``8c-production-collapse``). This module is pure glue over A1
(``gen_value_data.py`` + ``train_value.py``) and A2 (``eval_search.py`` +
the ``leaf_value="learned"`` agent): only the *trajectory policy* (heuristic ->
search agent) and the *dataset union* change. No new model, codec, or search.

The bounded design (the entire safety story)
--------------------------------------------
* **Hard cap of 2 iterations.** Never more.
* **Strict-improvement stop rule.** ``gate(V) = (worst_case_limit1_spins,
  rounds_to_finish)`` on the held-out ``900_000+`` band. An iteration is
  *retained* only if its gate strictly improves on the previous best
  (rounds-to-finish decreases OR worst-case limit-1 spins decreases, with
  NEITHER regressing). The first iteration whose gate does not strictly improve
  is **discarded** and iteration stops.
* **Best-checkpoint preservation.** The best-gating V seen so far (starting with
  the A1/A2 seed V) is always retained and shipped, so A3 can never ship a V that
  gates worse than A2's.
* **Train on the UNION of all data.** Every refit trains on the original A1
  heuristic dataset plus every prior A3 round's data -- never just the newest
  round -- guarding against catastrophic forgetting of heuristic-covered states.

Per iteration
-------------
1. **Generate** fresh MC value data with the CURRENT best V's A2 search agent on
   the TRAIN/VAL seed bands (``gen_value_data --policy learned --value-model
   <best V>``). A2's ``top_k``/``sim_budget`` knobs keep this affordable.
2. **Refit** V via the A1 trainer (``train_value``) on the UNION of all datasets
   so far (the A1 seed dataset + every A3 round). The union is materialized as a
   single merged ``.npz`` (concatenated parallel arrays + merged sidecar) so the
   unchanged ``train_value._load_dataset`` consumes it directly; the per-row
   track-disjoint ``split`` is preserved across the union.
3. **Re-gate** the refit V on the held-out ``900_000+`` band via ``eval_search``'s
   ``_run_field`` and apply the stop rule.

Usage:
    python experiments/value_iterate.py \\
        --seed-model checkpoints/value.zip \\
        --seed-data data/value_data.npz \\
        --workdir runs/value_iterate \\
        --iterations 2 --train-tracks 40 --val-tracks 12 --gate-games 24
"""

